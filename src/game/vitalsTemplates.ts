export function getHeartTemplateForHealth(health: number): string {
  if (health <= 0) return HEART_TEMPLATES.flat;
  if (health <= 25) return HEART_TEMPLATES.weak;
  if (health <= 60) return HEART_TEMPLATES.normal;
  if (health <= 85) return HEART_TEMPLATES.strong;
  return HEART_TEMPLATES.critical;
}

export function getBrainTemplateForActivity(activity: number): string {
  if (activity <= 10) return BRAIN_TEMPLATES.calm;
  if (activity <= 40) return BRAIN_TEMPLATES.focused;
  if (activity <= 75) return BRAIN_TEMPLATES.busy;
  return BRAIN_TEMPLATES.overload;
}
